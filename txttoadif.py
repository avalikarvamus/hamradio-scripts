from datetime import datetime
from zoneinfo import ZoneInfo

INPUT_FILE = "logill.txt"
OUTPUT_ADIF = "logill.adi"

LOCAL_TZ = ZoneInfo("Europe/Tallinn")
UTC_TZ = ZoneInfo("UTC")

BAND_CONFIG = {
    "2m":  {"freq": "145.450", "mode": "FM"},
    "70cm":{"freq": "433.450", "mode": "FM"},
    "4m":  {"freq": "70.450",  "mode": "SSB"},
    "6m":  {"freq": "50.450",  "mode": "SSB"}
}

def adif_field(name, value):
    return f"<{name}:{len(value)}>{value} "

with open(INPUT_FILE, encoding="utf-8") as f:
    lines = [line.strip() for line in f if line.strip()]

# ---- Päis ----
band = lines[0].lower()
contest_date = datetime.strptime(lines[1], "%d.%m.%Y")
my_call = lines[2].upper()
my_name = lines[3]
my_locator = lines[4].upper()

if band not in BAND_CONFIG:
    raise ValueError("Unknown band (accepts 70cm, 2m, 4m or 6m)")

freq = BAND_CONFIG[band]["freq"]
mode = BAND_CONFIG[band]["mode"]

qsos = lines[5:]

with open(OUTPUT_ADIF, "w", encoding="utf-8") as adif:
    adif.write("Generated by serial-number contest logger\n")
    adif.write("<EOH>\n")

    sent_serial = 1

    for qso in qsos:
        call, rcvd_serial, time_str = [x.strip() for x in qso.split(",")]

        call = call.upper()
        rcvd_serial = rcvd_serial.zfill(3)
        sent_str = str(sent_serial).zfill(3)

        local_dt = datetime.strptime(
            contest_date.strftime("%Y%m%d") + time_str,
            "%Y%m%d%H%M"
        ).replace(tzinfo=LOCAL_TZ)

        utc_dt = local_dt.astimezone(UTC_TZ)

        record = ""
        record += adif_field("CALL", call)
        record += adif_field("QSO_DATE", utc_dt.strftime("%Y%m%d"))
        record += adif_field("TIME_ON", utc_dt.strftime("%H%M"))
        record += adif_field("FREQ", freq)
        record += adif_field("MODE", mode)
        record += adif_field("STX", sent_str)
        record += adif_field("SRX", rcvd_serial)
        record += adif_field("STATION_CALLSIGN", my_call)
        record += adif_field("MY_GRIDSQUARE", my_locator)
        record += adif_field("OPERATOR", my_call)
        record += adif_field("NAME", my_name)
        record += "<EOR>\n"

        adif.write(record)
        sent_serial += 1

print("✅ ADIF log made:", OUTPUT_ADIF)