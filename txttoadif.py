import sys
import os
from datetime import datetime
from zoneinfo import ZoneInfo

# Check if a filename was provided
if len(sys.argv) < 2:
    print("Usage: python script_name.py <input_file> [manual_date]")
    print("Example with manual date: python script_name.py logill.txt 20231025")
    sys.exit(1)

# Get input file from command line argument
INPUT_FILE = sys.argv[1]

# Check if a second parameter (manual date) is provided
# If it exists, it will be used as the QSO_DATE in the ADIF records.
OVERRIDE_DATE = sys.argv[2] if len(sys.argv) > 2 else None

# Generate output filename by stripping extension and adding .adif
base_name = os.path.splitext(INPUT_FILE)[0]
OUTPUT_ADIF = base_name + ".adif"

LOCAL_TZ = ZoneInfo("Europe/Tallinn")
UTC_TZ = ZoneInfo("UTC")

BAND_CONFIG = {
    "2m":  {"freq": "145.450", "mode": "FM"},
    "70cm":{"freq": "433.450", "mode": "FM"},
    "4m":  {"freq": "70.450",  "mode": "SSB"},
    "6m":  {"freq": "50.450",  "mode": "SSB"}
}

def adif_field(name, value):
    return f"<{name}:{len(value)}>{value} "

# Read the file
try:
    with open(INPUT_FILE, encoding="utf-8") as f:
        lines = [line.strip() for line in f if line.strip()]
except FileNotFoundError:
    print(f"Error: File '{INPUT_FILE}' not found.")
    sys.exit(1)

if len(lines) < 5:
    print("Error: File is too short to contain required header information.")
    sys.exit(1)

# ---- Päis ----
band = lines[0].lower()
contest_date = datetime.strptime(lines[1], "%d.%m.%Y")
my_call = lines[2].upper()
my_name = lines[3]
my_locator = lines[4].upper()

if band not in BAND_CONFIG:
    raise ValueError(f"Unknown band ({band}). Accepted: {list(BAND_CONFIG.keys())}")

freq = BAND_CONFIG[band]["freq"]
mode = BAND_CONFIG[band]["mode"]

qsos = lines[5:]

# Write the ADIF file
with open(OUTPUT_ADIF, "w", encoding="utf-8") as adif:
    adif.write("Generated by serial-number contest logger\n")
    adif.write("<EOH>\n")

    sent_serial = 1

    for qso in qsos:
        parts = [x.strip() for x in qso.split(",")]
        if len(parts) < 3:
            continue
        
        call, rcvd_serial, time_str = parts[0], parts[1], parts[2]

        call = call.upper()
        rcvd_serial = rcvd_serial.zfill(3)
        sent_str = str(sent_serial).zfill(3)

        # Calculate local and UTC time to get the correct "TIME_ON" (HHMM)
        local_dt = datetime.strptime(
            contest_date.strftime("%Y%m%d") + time_str,
            "%Y%m%d%H%M"
        ).replace(tzinfo=LOCAL_TZ)

        utc_dt = local_dt.astimezone(UTC_TZ)

        # --- Date Logic ---
        # If a second parameter was provided (e.g., 20231025), use it as the date field.
        # Otherwise, use the calculated date from the log file.
        if OVERRIDE_DATE:
            qso_date_val = OVERRIDE_DATE
        else:
            qso_date_val = utc_dt.strftime("%Y%m%d")

        record = ""
        record += adif_field("CALL", call.capitalize())
        record += adif_field("QSO_DATE", qso_date_val)
        record += adif_field("TIME_ON", utc_dt.strftime("%H%M"))
        record += adif_field("FREQ", freq)
        record += adif_field("MODE", mode)
        record += adif_field("STX", sent_str)
        record += adif_field("SRX", rcvd_serial)
        record += adif_field("STATION_CALLSIGN", my_call)
        record += adif_field("MY_GRIDSQUARE", my_locator)
        record += adif_field("OPERATOR", my_call)
        record += adif_field("NAME", my_name)
        record += "<EOR>\n"

        adif.write(record)
        sent_serial += 1

print("✅ ADIF log made:", OUTPUT_ADIF)